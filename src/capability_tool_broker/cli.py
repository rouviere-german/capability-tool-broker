"""Command line entry point: ``capability-tool-broker`` or ``python -m capability_tool_broker``."""

from __future__ import annotations

import argparse
import json
import os
import sys
from pathlib import Path

__all__ = ["main"]

_ROLES = ("authority", "broker", "approver", "services")


def _serve(role: str, host: str | None, port: int | None) -> int:
    import uvicorn  # noqa: PLC0415 - only needed when serving

    from capability_tool_broker.core.config import get_settings  # noqa: PLC0415
    from capability_tool_broker.core.logging import configure_logging  # noqa: PLC0415
    from capability_tool_broker.core.tracing import install_global_tracer_provider  # noqa: PLC0415
    from capability_tool_broker.roles import build_app  # noqa: PLC0415

    settings = get_settings()
    configure_logging(settings.log_level, json_output=settings.log_json)
    app = build_app(role, settings)
    install_global_tracer_provider(app.state.tracer_provider)
    uvicorn.run(
        app,
        host=host or settings.host,
        port=port or settings.port,
        log_config=None,
        access_log=False,
        server_header=False,
    )
    return 0


def _keygen(out: Path, force: bool) -> int:
    from capability_tool_broker.stack import Keyset  # noqa: PLC0415

    if out.exists() and not force:
        print(f"{out} exists; pass --force to replace it", file=sys.stderr)
        return 1
    lines = [
        "# Generated by `capability-tool-broker keygen`. Contains secrets: never commit this file.",
        "# Each block belongs to exactly one compose service (see docker-compose.yml).",
    ]
    for role, variables in Keyset.generate().environment().items():
        lines.append(f"\n# --- {role} ---")
        lines.extend(f"{name}={value}" for name, value in variables.items())
    descriptor = os.open(out, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
    with os.fdopen(descriptor, "w", encoding="utf-8", newline="\n") as handle:
        handle.write("\n".join(lines) + "\n")
    print(f"wrote {out}", file=sys.stderr)
    return 0


def _sign_manifest(out: Path, body_path: Path | None) -> int:
    import yaml  # noqa: PLC0415

    from capability_tool_broker.broker.manifest import ManifestBody, sign_manifest  # noqa: PLC0415
    from capability_tool_broker.capabilities.keyfiles import load_ed25519_private  # noqa: PLC0415
    from capability_tool_broker.deploy import default_manifest_body  # noqa: PLC0415
    from capability_tool_broker.stack import MANIFEST_KEY_ID  # noqa: PLC0415

    key_text = os.environ.get("MANIFEST_SIGNING_KEY", "")
    if not key_text:
        print("MANIFEST_SIGNING_KEY is not set (see `keygen`)", file=sys.stderr)
        return 1
    if body_path is None:
        body = default_manifest_body()
    else:
        body = ManifestBody.model_validate(yaml.safe_load(body_path.read_text(encoding="utf-8")))
    signed = sign_manifest(body, load_ed25519_private(key_text), MANIFEST_KEY_ID)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(signed.to_json(), encoding="utf-8", newline="\n")
    print(f"wrote {out}", file=sys.stderr)
    return 0


def _review(answer: str) -> int:
    from capability_tool_broker.approver.cli import review_pending  # noqa: PLC0415
    from capability_tool_broker.roles import build_approver_service  # noqa: PLC0415
    from capability_tool_broker.settings import ApproverSettings  # noqa: PLC0415

    role = ApproverSettings()
    fixed = {"yes": "y", "no": "n"}.get(answer)
    decided = review_pending(
        build_approver_service(role),
        approver=role.reviewer,
        ask=(lambda prompt: fixed) if fixed is not None else input,
    )
    print(f"{len(decided)} request(s) decided")
    return 0


def _revoke(token_file: Path) -> int:
    import redis  # noqa: PLC0415

    from capability_tool_broker.broker.state import RedisStateStore  # noqa: PLC0415
    from capability_tool_broker.capabilities.keys import parse_identifier  # noqa: PLC0415
    from capability_tool_broker.macaroons import Macaroon, MacaroonFormatError  # noqa: PLC0415
    from capability_tool_broker.settings import BrokerSettings  # noqa: PLC0415

    role = BrokerSettings()
    if role.redis_url is None:
        print("BROKER_REDIS_URL is required to revoke tokens across processes", file=sys.stderr)
        return 1
    try:
        identifier = Macaroon.deserialize(token_file.read_text(encoding="utf-8").strip()).identifier
    except MacaroonFormatError:
        print("not a token", file=sys.stderr)
        return 1
    parsed = parse_identifier(identifier)
    if parsed is None:
        print("not a root-minted token", file=sys.stderr)
        return 1
    import time  # noqa: PLC0415

    store = RedisStateStore(redis.Redis.from_url(role.redis_url.get_secret_value()))
    store.revoke(parsed[1], until=None, now=int(time.time()))
    print(f"revoked token {parsed[1]} and every attenuation of it")
    return 0


def _e2e(phase: str) -> int:
    import httpx  # noqa: PLC0415

    from capability_tool_broker.agent.clients import (  # noqa: PLC0415
        ClientCredentials,
        HttpApproverClient,
        HttpAuthorityClient,
        HttpBrokerClient,
    )
    from capability_tool_broker.broker.manifest import ToolManifest  # noqa: PLC0415
    from capability_tool_broker.capabilities.keyfiles import (  # noqa: PLC0415
        load_ed25519_private,
        parse_public_key_map,
    )
    from capability_tool_broker.e2e import E2EError, resume_phase, start_phase  # noqa: PLC0415
    from capability_tool_broker.settings import AgentHostSettings  # noqa: PLC0415

    role = AgentHostSettings()
    credentials = ClientCredentials(
        role.client_id, load_ed25519_private(role.client_private_key.get_secret_value())
    )
    broker = HttpBrokerClient(httpx.Client(base_url=role.broker_url, timeout=10.0), credentials)
    approver = HttpApproverClient(
        httpx.Client(base_url=role.approver_url, timeout=10.0), credentials
    )
    manifest = ToolManifest.verify(
        broker.manifest(), parse_public_key_map(role.manifest_public_keys)
    )
    try:
        if phase == "start":
            authority = HttpAuthorityClient(
                httpx.Client(base_url=role.authority_url, timeout=10.0), credentials
            )
            summary = start_phase(
                authority=authority,
                broker=broker,
                approver=approver,
                manifest=manifest,
                state_path=role.state_path,
            )
        else:
            summary = resume_phase(
                broker=broker, approver=approver, manifest=manifest, state_path=role.state_path
            )
    except E2EError as exc:
        print(f"e2e {phase} FAILED: {exc}", file=sys.stderr)
        return 1
    print(json.dumps(summary, indent=2, sort_keys=True))
    return 0


def _demo(workdir: Path, interactive: bool) -> int:
    from capability_tool_broker.core.logging import configure_logging  # noqa: PLC0415
    from capability_tool_broker.demo import run_demo  # noqa: PLC0415

    configure_logging("WARNING", json_output=True, stream=sys.stderr)
    summary = run_demo(workdir, interactive=interactive)
    print("\nsummary:")
    print(json.dumps(summary, indent=2, sort_keys=True))
    return 0


def main(argv: list[str] | None = None) -> int:  # noqa: PLR0911 - one branch per command
    parser = argparse.ArgumentParser(prog="capability-tool-broker")
    sub = parser.add_subparsers(dest="command", required=True)

    serve = sub.add_parser("serve", help="run one role's HTTP service")
    serve.add_argument("role", choices=_ROLES)
    serve.add_argument("--host", default=None)
    serve.add_argument("--port", type=int, default=None)

    keygen = sub.add_parser("keygen", help="write a .env file with fresh per-role keys")
    keygen.add_argument("--out", type=Path, default=Path(".env"))
    keygen.add_argument("--force", action="store_true")

    sign = sub.add_parser("sign-manifest", help="sign the tool manifest (MANIFEST_SIGNING_KEY)")
    sign.add_argument("--out", type=Path, required=True)
    sign.add_argument("--body", type=Path, default=None)

    approver = sub.add_parser("approver", help="approver tools")
    approver_sub = approver.add_subparsers(dest="approver_command", required=True)
    review = approver_sub.add_parser("review", help="review pending approval requests")
    review.add_argument("--answer", choices=["ask", "yes", "no"], default="ask")

    revoke = sub.add_parser("revoke", help="revoke a token and all its attenuations")
    revoke.add_argument("--token-file", type=Path, required=True)

    e2e = sub.add_parser("e2e", help="end-to-end check against the compose stack")
    e2e.add_argument("phase", choices=["start", "resume"])

    sub.add_parser("generate-api-key", help="print a new API key and its SHA-256 digest")

    audit = sub.add_parser("audit", help="audit log tools")
    audit_sub = audit.add_subparsers(dest="audit_command", required=True)
    verify = audit_sub.add_parser("verify", help="verify a hash-chained audit log")
    verify.add_argument("path", type=Path)
    verify.add_argument("--expect-head", default=None)

    demo = sub.add_parser("demo", help="run the offline end-to-end demo")
    demo.add_argument("--workdir", type=Path, default=Path("var/demo"))
    demo.add_argument("--interactive", action="store_true", help="answer the approval yourself")

    args = parser.parse_args(argv)
    if args.command == "serve":
        return _serve(args.role, args.host, args.port)
    if args.command == "keygen":
        return _keygen(args.out, args.force)
    if args.command == "sign-manifest":
        return _sign_manifest(args.out, args.body)
    if args.command == "approver":
        return _review(args.answer)
    if args.command == "revoke":
        return _revoke(args.token_file)
    if args.command == "e2e":
        return _e2e(args.phase)
    if args.command == "generate-api-key":
        from capability_tool_broker.core.security import generate_api_key  # noqa: PLC0415

        raw, digest = generate_api_key()
        print(json.dumps({"api_key": raw, "api_key_sha256": digest}, indent=2))
        print("Store only api_key_sha256 in APP_API_KEY_SHA256.", file=sys.stderr)
        return 0
    if args.command == "audit":
        from capability_tool_broker.agentic.audit import main as audit_main  # noqa: PLC0415

        forwarded = ["verify", str(args.path)]
        if args.expect_head:
            forwarded += ["--expect-head", args.expect_head]
        return audit_main(forwarded)
    return _demo(args.workdir, args.interactive)


if __name__ == "__main__":
    raise SystemExit(main())
